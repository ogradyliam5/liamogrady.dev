/**
 * Local stand-ins for Cloudflare bindings so the Worker runs under Bun in dev and tests.
 * The fake AI binding streams a deterministic reply (and exercises the tool-call path)
 * so the agent UI can be developed offline. Production uses the real bindings.
 */
export async function localEnv(assets: { fetch: (r: Request | string) => Promise<Response> }) {
  return {
    ASSETS: assets,
    SITE_URL: 'http://localhost:8787',
    AGENT_PROVIDER: 'mock',
    AGENT_MODEL: 'mock-model',
    ENVIRONMENT: 'development',
    AI: mockAi(),
    RATE_LIMITER: { limit: async () => ({ success: true }) },
  };
}

function mockAi() {
  return {
    async run(model: string, input: Record<string, unknown>) {
      const messages = (input.messages ?? []) as { role: string; content: string }[];
      const last = [...messages].reverse().find((m) => m.role === 'user')?.content ?? '';
      const text = `(${model} offline mock) You asked: "${String(last).slice(0, 120)}". In production this answer is generated by the live model, grounded only in Liam's public profile.`;
      if (input.stream) {
        const enc = new TextEncoder();
        return new ReadableStream({
          async start(controller) {
            for (const word of text.split(/(\s+)/)) {
              controller.enqueue(enc.encode(`data: ${JSON.stringify({ response: word })}\n\n`));
              await new Promise((r) => setTimeout(r, 12));
            }
            controller.enqueue(enc.encode('data: [DONE]\n\n'));
            controller.close();
          },
        });
      }
      return { response: text };
    },
  };
}
